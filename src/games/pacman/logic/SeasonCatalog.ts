export function seasonForLevel(level: number): SeasonData {
	if (!Number.isFinite(level) || level < 1) {
		console.error('SeasonCatalog.seasonForLevel', 'invalid level', level);
		return SEASONS[0]!;
	}
	const index = (Math.floor(level) - 1) % SEASONS.length;
	const season = SEASONS[index];
	if (!season) {
		console.error('SeasonCatalog.seasonForLevel', 'missing season', { level, index });
		return SEASONS[0]!;
	}
	return season;
}