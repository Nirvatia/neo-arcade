import type { Biome } from './Biome.js';

/**
 * Описание биома для реестра.
 *
 * Биом регистрируется не самим классом, а дескриптором:
 * - id удобен для отладки, кэшей и будущих сохранений;
 * - infinite помечает последний бесконечный биом;
 * - create позволяет создавать биом лениво и без жёсткой привязки к конструктору.
 */
export interface BiomeDescriptor {
	readonly id: string;
	/**
	 * Бесконечный биом.
	 *
	 * Такой биом не открывает выход, не имеет финальной последовательности
	 * и играет бесконечно.
	 */
	readonly infinite?: boolean;
	create: () => Biome;
}

/**
 * Стратегия выбора биома по уровню.
 *
 * Получает глобальный уровень и размер реестра,
 * возвращает индекс биома.
 */
export type BiomeResolver = (level: number, registryLength: number) => number;